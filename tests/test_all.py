def test_bsgs_small_groups_against_brute_force():
    rng = np.random.default_rng(0)
    for n in (5, 6):
        gens = [rng.permutation(n) for _ in range(2)]
        seen = {tuple(range(n))}
        frontier = [np.arange(n)]
        while frontier:
            nxt = []
            for p in frontier:
                for g in gens:
                    q = p[g]
                    if tuple(q) not in seen:
                        seen.add(tuple(q))
                        nxt.append(q)
            frontier = nxt
        b = BSGS(n, gens)
        assert b.order == len(seen)
        assert all(b.contains(np.array(p)) for p in list(seen)[:200])
    assert BSGS(4, [np.arange(4)]).order == 1


