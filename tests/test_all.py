@pytest.mark.parametrize("name", ["cube3", "fifteen", "megaminx", "rubiks_clock", "pancake"])
def test_vectorised_env_matches_reference(name):
    pz = get_puzzle(name)
    tp = TensorPuzzle(pz, "cpu")
    rng = np.random.default_rng(0)
    B = 16
    ref = [pz.identity.copy() for _ in range(B)]
    P = tp.solved(B)
    for _ in range(30):
        acts = []
        for b in range(B):
            a = int(rng.choice(pz.legal_actions(ref[b])))
            ref[b] = pz.apply(ref[b], a)
            acts.append(a)
        P = tp.apply(P, torch.tensor(acts))
    assert np.array_equal(P.numpy(), np.stack(ref))
    children, legal = tp.expand(P)
    assert children.shape == (B, pz.num_actions, pz.n)
    for a in range(pz.num_actions):
        assert torch.equal(children[:, a], tp.apply(P, torch.full((B,), a)))
    assert np.array_equal(legal.numpy(), np.stack([pz.legal[:, pz.anchor_pos(r)] for r in ref]))
    assert np.array_equal(tp.colors(P).numpy(), np.stack([pz.colors(r) for r in ref]))
    assert tp.is_solved(tp.solved(3)).all() and not tp.is_solved(P).all()


def test_random_walk_and_vec_env():
    pz = get_puzzle("cube2")
    tp = TensorPuzzle(pz, "cpu")
    P = tp.random_walk(64, torch.zeros(64, dtype=torch.long))
    assert tp.is_solved(P).all()
    grp = group("cube2")
    P = tp.random_walk(64, torch.randint(1, 15, (64,)))
    assert all(grp.contains_state(p) for p in P.numpy())
    one = tp.random_walk(256, torch.ones(256, dtype=torch.long))
    assert not tp.is_solved(one).any()
    env = VecPuzzleEnv(pz, num_envs=32, device="cpu", max_steps=5, scramble_depth=(1, 1), seed=0)
    obs = env.reset()
    assert obs.shape == (32, pz.n) and obs.dtype == torch.long
    # undo the single scramble move by brute force: one of the actions solves each env
    children, _ = env.tp.expand(env.state)
    solving = env.tp.is_solved(children.reshape(-1, pz.n)).view(32, -1).float().argmax(1)
    obs, reward, term, trunc, info = env.step(solving)
    assert term.all() and (reward == -1).all() and not trunc.any()
    assert not env.tp.is_solved(env.state).all()            # auto-reset re-scrambled
    for _ in range(5):
        _, _, term, trunc, _ = env.step(torch.zeros(32, dtype=torch.long))
    assert (term | trunc | (env.steps < 5)).all()


