def test_stabilizer_curriculum_chain():
    for name in ("cube3", "megaminx", "fifteen", "rubiks_clock"):
        grp = group(name)
        cur = grp.stabilizer_curriculum(4)
        orders = [s.order for s in cur.stages]
        assert orders[0] == grp.order and orders[-1] == 1
