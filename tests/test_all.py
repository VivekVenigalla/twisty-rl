def test_parity_traps_are_detected_instantly():
    pz, grp = get_puzzle("cube3"), group("cube3")
    rng = np.random.default_rng(5)
    P, _ = pz.scramble(rng, 40)
    assert grp.is_solvable(P)
    C = pz.colors(P)
    assert np.array_equal(grp.state_from_colors(C), P)
    pieces = {k: [p.facets for p in pz.spec.pieces if p.kind == k] for k in ("edge", "corner")}
    loc = lambda f: int(np.nonzero(P == f)[0][0])
    # single edge flip
    e = [loc(f) for f in pieces["edge"][0]]
    bad = P.copy(); bad[e] = bad[e[::-1]]
    assert not grp.is_solvable(bad) and not grp.is_solvable(pz.colors(bad), colors=True)
    # single corner twist
    c = [loc(f) for f in pieces["corner"][0]]
    bad = P.copy(); bad[c] = bad[[c[1], c[2], c[0]]]
    assert not grp.is_solvable(bad)
    # swap of two edges (odd permutation of pieces)
    e2 = [loc(f) for f in pieces["edge"][1]]
    bad = P.copy(); bad[e], bad[e2] = P[e2], P[e]
    assert not grp.is_solvable(bad)
    # two flips cancel
    good = P.copy(); good[e] = good[e[::-1]]; good[e2] = good[e2[::-1]]
    assert grp.is_solvable(good)
    # 15-puzzle: the classic 14-15 swap
    fz, fg = get_puzzle("fifteen"), group("fifteen")
    S = fz.identity.copy(); S[[13, 14]] = S[[14, 13]]
    assert not fg.is_solvable(S) and not fg.is_solvable(fz.colors(S), colors=True)
    Q, _ = fz.scramble(rng, 60)
    assert fg.is_solvable(Q) and fg.is_solvable(fz.colors(Q), colors=True)
    # megaminx corner twist
    mz, mg = get_puzzle("megaminx"), group("megaminx")
    corner = next(p.facets for p in mz.spec.pieces if p.kind == "corner")
    T = mz.identity.copy(); T[corner] = T[[corner[1], corner[2], corner[0]]]
    assert not mg.is_solvable(T) and mg.is_solvable(mz.scramble(rng, 30)[0])


