    assert canon.num_symmetries == 48 == len(pz.valid_symmetries())
    h = plain.hash(tp.from_numpy(P))
    assert len(set(h.tolist())) == 6 and (h > 0).all() and (h < 2 ** 62).all()
    assert torch.equal(h, plain.hash(tp.from_numpy(P)))
    hc = canon.hash(tp.from_numpy(P))
    for rho, pi in pz.valid_symmetries()[1:8]:
        for i in range(3):
            sym_colors = pi[pz.colors(P[i])[rho]]
            Q = grp.state_from_colors(sym_colors)             # symmetric image is itself reachable
            assert Q is not None
            assert int(canon.hash(tp.from_numpy(Q))[0]) == int(hc[i])
            assert true_len_equal(pz, P[i], Q)
