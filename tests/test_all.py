def test_macro_promotion_extends_action_space_and_graph():
    pz = get_puzzle("cube3")
    miner = MacroMiner(pz, 3, 1)
    macros = miner.promote(miner.mine(top_k=8), 2)
    ext = pz.with_macros(macros)
    assert ext.num_actions > pz.num_actions and ext.num_primitive == pz.num_primitive
    for a in range(pz.num_actions, ext.num_actions):
        word = ext.action_words[a]
        assert np.array_equal(ext.table[a, 0], pz.apply_word(pz.identity, word))
        assert ext.cost[a] == len(word)
        assert np.array_equal(ext.table[a, 0][ext.table[ext.inverse[a], 0]], pz.identity)
    g0, g1 = compile_graph(pz), compile_graph(ext)
    assert macro_edge_count(g0) == 0 and macro_edge_count(g1) > 0
    assert g1.num_edges == g0.num_edges + macro_edge_count(g1)
    assert ext.expand_to_primitive([ext.num_actions - 1]) == list(ext.action_words[-1])
    # sliding-puzzle macros are conditional: legal exactly where every step is legal
    fz = get_puzzle("fifteen")
    fm = MacroMiner(fz)
    fext = fz.with_macros(fm.promote(fm.mine(4), 1))
    a = fz.num_actions
    assert fext.legal[a, 15] and not fext.legal[a].all()
    assert np.array_equal(fext.apply(fext.identity, a), fz.apply_word(fz.identity, fext.action_words[a]))


