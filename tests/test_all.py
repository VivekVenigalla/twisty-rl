def _relabelled(pz: Puzzle, sigma: np.ndarray) -> Puzzle:
    """Isomorphic copy of ``pz`` with facet ``i`` renamed ``sigma[i]`` and actions listed in reverse."""
    n = pz.n
    inv = invert_perm(sigma)
    solved = pz.solved_colors[inv].tolist()
    gens = []
    for gi in reversed(range(len(pz.spec.generators))):
        m = pz.table[gi, 0]
        gens.append(GeneratorSpec(name=pz.spec.generators[gi].name, perm=sigma[m[inv]].tolist()))
    pieces = [PieceSpec(name=p.name, kind=p.kind, facets=sorted(sigma[p.facets].tolist())) for p in pz.spec.pieces]
    return Puzzle(PuzzleSpec(name=pz.name + "_relabelled", n=n, solved_state=solved, generators=gens, pieces=pieces))


