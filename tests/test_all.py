def test_group_axioms_on_generated_group():
    g = group("cube2").bsgs
    rng = np.random.default_rng(1)
    ident = np.arange(g.n)
    for _ in range(40):
        a, b, c = (g.random_element(rng) for _ in range(3))
        assert g.contains(compose(a, b))                                         # closure
        assert np.array_equal(compose(compose(a, b), c), compose(a, compose(b, c)))  # associativity
        assert np.array_equal(compose(a, ident), a) and np.array_equal(compose(ident, a), a)
        ainv = invert_perm(a)
        assert g.contains(ainv) and np.array_equal(compose(a, ainv), ident)      # inverses
    assert g.contains(ident)


