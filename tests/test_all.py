def test_spectral_encodings_are_laplacian_eigenvectors():
    pz = get_puzzle("cube2")
    W = topology_adjacency(pz)
    assert np.array_equal(W, W.T)
    pe, lam, mask, rw, diff = spectral_encodings(W, 8, 6)
    deg = W.sum(1)
    d = np.where(deg > 0, 1 / np.sqrt(np.maximum(deg, 1e-12)), 0)
    L = np.eye(pz.n) - d[:, None] * W * d[None, :]
    L[deg == 0, deg == 0] = 0
    for k in range(int(mask.sum())):
        v = pe[:, k]
        assert np.allclose(L @ v, lam[k] * v, atol=1e-8) and lam[k] > 1e-8
    assert np.all(rw >= -1e-12) and np.all(rw <= 1 + 1e-12)
    assert np.allclose(diff[..., 0], diff[..., 0].T)


